/**
 * One-time / maintenance: convert public/doors/*.png → public/images/{model}.webp
 * and regenerate data/doors.js + backend/data/doors.js
 *
 * Run: node scripts/build-doors-catalog.cjs
 */
const fs = require('fs');
const path = require('path');
const sharp = require('sharp');

const ROOT = path.join(__dirname, '..');
const DOORS_SRC = path.join(ROOT, 'public', 'doors');
const IMAGES_OUT = path.join(ROOT, 'public', 'images');
const OUT_FILES = [
  path.join(ROOT, 'data', 'doors.js'),
  path.join(ROOT, 'backend', 'data', 'doors.js')
];

const TYPES = ['Неоклассика', 'Современная', 'Классика', 'Лофт', 'Скандинавская', 'Минимализм'];
const STYLES = ['Минимализм', 'Классика', 'Хай-тек', 'Скандинавский', 'Ретро', 'Индастриал', 'Арт-деко'];
const COLORS = [
  'Серо-зелёный', 'Глиняный', 'Антрацит', 'Слоновая кость', 'Тёплый песок', 'Графит', 'Капучино', 'Натуральный дуб',
  'Венге', 'Орех', 'Снежно-белый', 'Серый камень', 'Терракота', 'Оливковый', 'Перламутр', 'Молочный',
  'Дымчато-серый', 'Кофе с молоком', 'Синий индиго', 'Пудровый розовый', 'Бирюзовый', 'Морская соль', 'Песочный',
  'Коричневый мокко', 'Серебристый', 'Бордовый', 'Изумрудный', 'Пепельный', 'Светлый венге', 'Натуральный беж',
  'Серо-коричневый', 'Пепельно-синий', 'Миндальный', 'Мокко', 'Туманно-серый', 'Светлый дуб', 'Сланцевый',
  'Дуб натуральный'
];

function sortDoorFiles(a, b) {
  const parse = (f) => {
    const m = f.match(/^doors-(\d+)(?:_(\d+))?\.png$/i);
    if (!m) return { base: 0, sub: 0 };
    return { base: parseInt(m[1], 10), sub: m[2] ? parseInt(m[2], 10) : 0 };
  };
  const A = parse(a);
  const B = parse(b);
  if (A.base !== B.base) return A.base - B.base;
  return A.sub - B.sub;
}

function fileToModel(filename) {
  return filename.replace(/^doors-/i, '').replace(/\.png$/i, '');
}

function descriptionFor(model) {
  return `Модель ${model} — входная дверь премиум-коллекции Kukcha. Подходит для квартиры и загородного дома, сочетается с современным и классическим интерьером.`;
}

async function main() {
  const pngFiles = fs.readdirSync(DOORS_SRC).filter((f) => f.endsWith('.png'));
  if (pngFiles.length === 0) {
    console.error('No PNG files in', DOORS_SRC);
    process.exit(1);
  }
  pngFiles.sort(sortDoorFiles);

  fs.mkdirSync(IMAGES_OUT, { recursive: true });

  const catalog = [];
  let id = 1;

  for (const file of pngFiles) {
    const model = fileToModel(file);
    const outName = `${model}.webp`;
    const outPath = path.join(IMAGES_OUT, outName);
    const inPath = path.join(DOORS_SRC, file);

    await sharp(inPath)
      .webp({ quality: 86 })
      .toFile(outPath);

    const idx = (id - 1) % COLORS.length;
    catalog.push({
      id,
      model,
      type: TYPES[(id - 1) % TYPES.length],
      style: STYLES[(id - 1) % STYLES.length],
      color: COLORS[idx],
      size: '2.40 x 0.90',
      fill: '80%',
      description: descriptionFor(model),
      image: `/images/${outName}`
    });
    id += 1;
  }

  const js = `/* Auto-generated by scripts/build-doors-catalog.cjs — do not edit by hand; run the script to refresh */
const doors = ${JSON.stringify(catalog, null, 2)};

module.exports = doors;
`;

  for (const f of OUT_FILES) {
    fs.mkdirSync(path.dirname(f), { recursive: true });
    fs.writeFileSync(f, js, 'utf8');
    console.log('Wrote', f);
  }
  console.log('Converted', catalog.length, 'images to', IMAGES_OUT);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
